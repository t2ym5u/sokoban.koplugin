#!/bin/bash
# Rebuilds ../levels_data.lua: generator runs in parallel (fixed seeds, so the
# result is deterministic), then merge_levels.lua dedupes, re-verifies every
# level (solution replay + A* optimality proof) and writes the bank.
# Takes about 30 min on an 8-core desktop, most of it the expert band.
#   gen_levels.lua <count> <seed> <min boxes> <max boxes> <min pushes> <max pushes> <climb steps> <wall mutation>
set -e
here="$(cd "$(dirname "$0")" && pwd)"
tmp="$(mktemp -d)"
G="$here/gen_levels.lua"
run() { out="$1"; shift; luajit "$G" "$@" > "$tmp/$out.txt" 2> "$tmp/$out.log"; }
run b1 110 11 2 3 5 12 10 0.4 &
run i1 110 21 2 4 13 22 20 0.4 &
for s in 31 32; do run a$s 50 $s 3 5 23 32 40 0.4 & done
for s in 51 52 53 54 55 56; do run x$s 12 $s 3 6 33 999 60 0.4 & done
wait
out="$here/../levels_data.lua"
{
    echo "-- Level bank, generated by tools/build_levels.sh -- do not edit by hand."
    echo "-- One band header per difficulty, then one line per level: its optimal"
    echo "-- push count, a solution in LURD notation (lower case = step, upper case"
    echo "-- = push) achieving it, and the map, rows joined by \"|\" (XSB symbols)."
    echo "-- Kept as a .lua file so PluginManager ships it (it fetches .lua files only)."
    echo "return [["
    luajit "$here/merge_levels.lua" 100 "$tmp"/*.txt
    echo "]]"
} > "$out"
rm -rf "$tmp"
